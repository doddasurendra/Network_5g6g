    "\n",
    "# 4. Classical Ground-Truth Optimum\n",
    "def solve_classical_ground_truth(Q: np.ndarray) -> Dict[str, Any]:\n",
    "    n = Q.shape[0]\n",
    "    best_e, best_bit = float('inf'), None\n",
    "    for i in range(1 << n):\n",
    "        x = np.array([(i >> bit) & 1 for bit in range(n)], dtype=float)\n",
    "        e = float(x.T @ Q @ x)\n",
    "        if e < best_e:\n",
    "            best_e = e\n",
    "            best_bit = ''.join(str(int(b)) for b in x)\n",
    "    return {'optimal_energy': best_e, 'optimal_bitstring': best_bit}\n",
    "\n",
    "# 5. Parameterized QAOA Quantum Circuit Engine\n",
    "class QAOAExecutionEngine:\n",
    "    @staticmethod\n",
    "    def build_qaoa_circuit(Q: np.ndarray, p: int = 1, gammas: List[float] = [0.5], betas: List[float] = [0.5]):\n",
    "        n = Q.shape[0]\n",
    "        qc = QuantumCircuit(n, n)\n",
    "        qc.h(range(n))\n",
    "        for l in range(p):\n",
    "            g, b = gammas[l], betas[l]\n",
    "            for i in range(n):\n",
    "                if abs(Q[i, i]) > 1e-5: qc.rz(g * Q[i, i], i)\n",
    "            for i in range(n):\n",
    "                for j in range(i + 1, n):\n",
    "                    coeff = Q[i, j] + Q[j, i]\n",
    "                    if abs(coeff) > 1e-5:\n",
    "                        qc.cx(i, j)\n",
    "                        qc.rz(g * coeff * 0.5, j)\n",
    "                        qc.cx(i, j)\n",
    "            for i in range(n): qc.rx(2.0 * b, i)\n",
    "        qc.measure(range(n), range(n))\n",
    "        return qc\n",
    "    def execute_simulator(self, Q: np.ndarray, p: int = 1, shots: int = 1024):\n",
    "        sim = AerSimulator()\n",
    "        n = Q.shape[0]\n",
    "        def cost(params):\n",
    "            qc = self.build_qaoa_circuit(Q, p=p, gammas=params[:p], betas=params[p:])\n",
    "            counts = sim.run(qc, shots=shots).result().get_counts()\n",
    "            tot = 0.0\n",
    "            for bstr, cnt in counts.items():\n",
    "                x = np.array([int(bit) for bit in reversed(bstr)], dtype=float)\n",
    "                tot += float(x.T @ Q @ x) * cnt\n",
    "            return tot / shots\n",
    "        res = minimize(cost, [0.45, 0.45], method='COBYLA', options={'maxiter': 16})\n",
    "        best_qc = self.build_qaoa_circuit(Q, p=p, gammas=res.x[:p], betas=res.x[p:])\n",
    "        counts = sim.run(best_qc, shots=shots).result().get_counts()\n",
    "        best_e, best_bit = float('inf'), None\n",
    "        for bstr in counts:\n",
    "            x = np.array([int(bit) for bit in reversed(bstr)], dtype=float)\n",
