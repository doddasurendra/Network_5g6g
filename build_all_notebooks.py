    "# 3. Exact Mathematical QUBO Formulation\n",
    "class QUBOBuilder:\n",
    "    @staticmethod\n",
    "    def build_spectrum_qubo(num_cells=3, num_channels=3, penalty=3.0, cost_weight=1.0, alloc_weight=8.0):\n",
    "        n = num_cells * num_channels\n",
    "        Q = np.zeros((n, n), dtype=float)\n",
    "        idx = lambda c, f: c * num_channels + f\n",
    "        # One channel per cell constraint\n",
    "        for c in range(num_cells):\n",
    "            for f in range(num_channels):\n",
    "                u = idx(c, f)\n",
    "                Q[u, u] += -alloc_weight\n",
    "                for f2 in range(f + 1, num_channels):\n",
    "                    v = idx(c, f2)\n",
    "                    Q[u, v] += 2.0 * alloc_weight\n",
    "        # Adjacent cell co-channel interference penalty\n",
    "        interferences = [(0, 1), (1, 2)] if num_cells >= 3 else [(0, 1)]\n",
    "        if num_cells >= 4:\n",
    "            interferences.append((2, 3))\n",
    "        for c1, c2 in interferences:\n",
    "            for f in range(num_channels):\n",
    "                u = idx(c1, f)\n",
    "                v = idx(c2, f)\n",
    "                Q[min(u, v), max(u, v)] += penalty * 2.0\n",
    "        # Operational cost per channel\n",
    "        for c in range(num_cells):\n",
    "            for f in range(num_channels):\n",
    "                Q[idx(c, f), idx(c, f)] += cost_weight * (f + 1) * 0.25\n",
    "        return Q, n\n",
    "\n",
